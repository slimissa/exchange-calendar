#!/usr/bin/env python3
"""
check_doc_facts.py — Fails CI when a number written in the markdown disagrees
with docs/facts.json.

docs/facts.json (generated by tools/update_facts.py) records the countable
facts about the registry. This script scans the prose of the documents below
for sentences that assert one of them and compares the number.

Scanned by default: README.md, BLOCKED.md, CONTRIBUTING.md,
docs/CONSUMERS.md, docs/FETCHERS.md. Fenced code blocks are skipped. A claim
is read from one line; a sentence wrapped across lines is not matched.

Which sentences count
---------------------
Each claim is a fixed phrase with a number (digits, or a word from zero to
ninety-nine such as "Seventy-four" or "twenty") in front of or inside it. The
phrases are listed in CLAIMS below. A bare "N exchanges" is NOT a claim: the
README also says "67 exchanges" for the Saturday-Sunday week, which is a
different number. Add a pattern to CLAIMS when you write a new kind of
countable sentence.

Silent failure
--------------
Every scanned file must contain at least one claim. If rewording removes all
of a file's claims, the check exits 2 instead of passing on nothing.

Exit codes
----------
    0  every claim matches
    1  at least one claim is wrong (file, line, expected, actual are printed)
    2  usage or read problem: facts.json missing or malformed, a file missing,
       or a scanned file with no claim at all

Usage
-----
    python3 tools/check_doc_facts.py
    python3 tools/check_doc_facts.py --files README.md docs/CONSUMERS.md
    python3 tools/check_doc_facts.py --root /path/to/repo
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_FILES = [
    "README.md",
    "BLOCKED.md",
    "CONTRIBUTING.md",
    "docs/CONSUMERS.md",
    "docs/FETCHERS.md",
]

_UNITS = ("zero one two three four five six seven eight nine ten eleven twelve thirteen "
          "fourteen fifteen sixteen seventeen eighteen nineteen").split()
_TENS = "twenty thirty forty fifty sixty seventy eighty ninety".split()
WORDS = {w: i for i, w in enumerate(_UNITS)}
for _i, _t in enumerate(_TENS):
    WORDS[_t] = 20 + 10 * _i
    for _j in range(1, 10):
        WORDS[f"{_t}-{_UNITS[_j]}"] = 20 + 10 * _i + _j

# Longest words first so "seventy-four" wins over "seventy".
NUM = r"(\d+|" + "|".join(sorted((re.escape(w) for w in WORDS), key=len, reverse=True)) + r")"
TICK = "`"


def to_int(token: str) -> int:
    t = token.lower().replace(" ", "-")
    return int(t) if t.isdigit() else WORDS[t]


# (fact name, expression over the facts, regex with the number as group 1)
# Patterns are matched case-insensitively against one line of prose.
CLAIMS: list[tuple[str, str, str]] = [
    ("exchanges_total", "exchanges_total", NUM + r" exchanges across\b"),
    ("exchanges_total", "exchanges_total", r"\b" + NUM + r" exchanges\."),
    ("exchanges_total", "exchanges_total", r"\b\d+ of " + NUM + r" registry exchanges"),
    ("exchanges_total", "exchanges_total", r"\ball " + NUM + r" (?:registry )?exchanges\b"),
    ("exchanges_total", "exchanges_total", r"\b" + NUM + r" exchange (?:JSON )?files\b"),
    ("exchanges_total", "exchanges_total", r"\bwith " + NUM + r" exchanges\b"),
    ("fetchers_registered", "fetchers_implemented + fetchers_ci_unreachable + fetchers_blocked",
     r"\b" + NUM + r" have registered fetchers"),
    ("fetchers_registered", "fetchers_implemented + fetchers_ci_unreachable + fetchers_blocked",
     r"\b" + NUM + r" of \d+ registry exchanges have automated fetchers"),
    ("fetchers_registered", "fetchers_implemented + fetchers_ci_unreachable + fetchers_blocked",
     r"\bfor the " + NUM + r" fetchers registered"),
    ("fetchers_implemented", "fetchers_implemented",
     r"\b" + NUM + r" verified against live sources"),
    ("fetchers_ci_unreachable + fetchers_blocked", "fetchers_ci_unreachable + fetchers_blocked",
     r"\b" + NUM + r" documented as ci-unreachable"),
    ("exchanges_no_fetcher", "exchanges_no_fetcher", r"\bremaining " + NUM + r" have no fetcher"),
    ("exchanges_blocked_total", "exchanges_blocked_total",
     r"\b" + NUM + r" exchanges are blocked\b"),
    ("exchanges_blocked_total", "exchanges_blocked_total",
     r"\bnone of the " + NUM + r" blocked entries"),
    ("sql_files", "sql_files", r"\b" + NUM + r" " + TICK + r"?exchange_calendar\*\.sql" + TICK + r"? files"),
    ("csv_tsv_files", "csv_tsv_files",
     r"\b" + NUM + r" " + TICK + r"exchange_calendar\.TABLE\*\.csv" + TICK + r" and " + TICK + r"\.tsv" + TICK + r" files"),
    ("csv_tsv_files", "csv_tsv_files", r"\bdialects, " + NUM + r" files"),
    ("parquet_files", "parquet_files",
     r"\b" + NUM + r" " + TICK + r"exchange_calendar\.TABLE\.parquet" + TICK + r" files"),
]
COMPILED = [(name, expr, re.compile(rx, re.IGNORECASE)) for name, expr, rx in CLAIMS]


class ReadProblem(Exception):
    """Raised for anything that should exit 2."""


def evaluate(expr: str, facts: dict) -> int:
    try:
        return sum(facts[t.strip()] for t in expr.split("+"))
    except KeyError as exc:
        raise ReadProblem(f"facts.json has no fact {exc.args[0]!r}") from None


def prose_lines(text: str):
    """(line number, line) outside fenced code blocks."""
    fenced = False
    for n, line in enumerate(text.splitlines(), 1):
        if line.lstrip().startswith(("```", "~~~")):
            fenced = not fenced
            continue
        if not fenced:
            yield n, line


def scan(text: str, facts: dict) -> tuple[list[dict], int]:
    """Return (wrong claims, number of claims found) for one document."""
    wrong: list[dict] = []
    found = 0
    for n, line in prose_lines(text):
        for name, expr, rx in COMPILED:
            for m in rx.finditer(line):
                found += 1
                actual = to_int(m.group(1))
                expected = evaluate(expr, facts)
                if actual != expected:
                    wrong.append({"line": n, "fact": name, "expected": expected,
                                  "actual": actual, "text": m.group(0)})
    return wrong, found


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--root", type=Path, default=REPO_ROOT, help="repository root")
    p.add_argument("--files", nargs="+", help="files to scan, relative to the root")
    args = p.parse_args(argv)
    root = args.root
    try:
        facts = json.loads((root / "docs" / "facts.json").read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        print(f"error: cannot read docs/facts.json: {exc}", file=sys.stderr)
        return 2
    if not isinstance(facts, dict):
        print("error: docs/facts.json is not a JSON object", file=sys.stderr)
        return 2
    bad = 0
    total = 0
    try:
        for rel in args.files or DEFAULT_FILES:
            try:
                text = (root / rel).read_text(encoding="utf-8")
            except OSError as exc:
                raise ReadProblem(f"cannot read {rel}: {exc}") from None
            wrong, found = scan(text, facts)
            if found == 0:
                raise ReadProblem(
                    f"{rel}: no claim found. Either the prose was reworded away from every "
                    "pattern in tools/check_doc_facts.py, or the file should not be scanned."
                )
            total += found
            for w in wrong:
                bad += 1
                print(f"{rel}:{w['line']}: says {w['actual']} but facts.json has {w['expected']} "
                      f"for {w['fact']}: \"{w['text']}\"")
    except ReadProblem as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    if bad:
        print(f"\n{bad} claim(s) disagree with docs/facts.json. Fix the prose; "
              "if the tree changed, run tools/update_facts.py first.")
        return 1
    print(f"OK: {total} claim(s) in {len(args.files or DEFAULT_FILES)} file(s) match docs/facts.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
